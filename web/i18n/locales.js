export function resolveLocale(requested) {
  const candidates = Array.isArray(requested) ? requested : [requested];
  const tags = LOCALE_META.map((item) => item.tag);
  for (const candidate of candidates.filter(Boolean)) {
    const exact = tags.find(
      (tag) => tag.toLowerCase() === String(candidate).toLowerCase(),
    );
    if (exact) return exact;
    const base = String(candidate).split("-")[0].toLowerCase();
    const baseMatch = tags.find((tag) => tag.toLowerCase() === base);
    if (baseMatch) return baseMatch;
  }
  return "en";
}

export function getLocaleMeta(locale) {
  const resolved = resolveLocale(locale);
  return LOCALE_META.find((item) => item.tag === resolved) ?? LOCALE_META[1];
}

export function getCatalog(locale) {
  const resolved = resolveLocale(locale);
  if (resolved === "pl") return POLISH_CATALOG;
  if (resolved === "en") return ENGLISH_CATALOG;
  const base = resolved.split("-")[0];
  return Object.freeze({
    ...ENGLISH_CATALOG,
    ...(PARTIAL_CATALOGS[base] ?? {}),
    ...(PARTIAL_CATALOGS[resolved] ?? {}),
  });
}

export function translate(locale, key, values = {}) {
  const catalog = getCatalog(locale);
  const template = catalog[key] ?? ENGLISH_CATALOG[key] ?? "";
  return String(template).replace(/\{(\w+)\}/g, (_, name) =>
    values[name] == null ? `{${name}}` : String(values[name]),
  );
}

export function applyDocumentLocale(locale) {
  const meta = getLocaleMeta(locale);
  document.documentElement.lang = meta.tag;
  document.documentElement.dir = meta.direction;
  return meta;
}

export function detectInitialLocale(storedLocale, browserLocales = []) {
  return resolveLocale(storedLocale || browserLocales);
}
